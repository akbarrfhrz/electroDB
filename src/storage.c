static int code_equals_ignore_case(const char *left, const char *right) {
    while (*left && *right) {
        if (tolower((unsigned char)*left) != tolower((unsigned char)*right)) {
            return 0;
        }
        left++;
        right++;
    }
    return *left == '\0' && *right == '\0';
}

static int seed_code_exists(const Component list[], int count, const char *code) {
    for (int i = 0; i < count; i++) {
        if (code_equals_ignore_case(list[i].code, code)) {
            return 1;
        }
    }
    return 0;
}

static int seed_id_exists(const Component list[], int count, int id) {
    for (int i = 0; i < count; i++) {
        if (list[i].id == id) {
            return 1;
        }
    }
    return 0;
}

static void append_seed_expansion(Component list[], int *count, int *next_id) {
    int seed_count = 0;
    int seed_next_id = 1;
    storage_seed_defaults(seed_catalog, &seed_count, &seed_next_id);

    for (int i = 10; i < seed_count && *count < MAX_COMPONENTS; i++) {
        if (seed_code_exists(list, *count, seed_catalog[i].code)) {
            continue;
        }

        int id = *next_id;
        while (id <= 0 || seed_id_exists(list, *count, id)) {
            id++;
        }
        seed_catalog[i].id = id;
        list[*count] = seed_catalog[i];
        (*count)++;
        *next_id = id + 1;
    }
}

int storage_save(const Component list[], int count, int next_id) {
    storage_ensure_dir();
    FILE *fp = fopen(DB_FILE_PATH, "wb");
    if (!fp) {
        return 0;
    }

    FileHeader header;
    memset(&header, 0, sizeof(header));
    memcpy(header.magic, "ELDBv4", 7);
    header.count = count;
    header.next_id = next_id;
    header.seed_version = CATALOG_SEED_VERSION;

    if (fwrite(&header, sizeof(FileHeader), 1, fp) != 1) {
        fclose(fp);
        return 0;
    }

    if (count > 0) {
        if ((int)fwrite(list, sizeof(Component), (size_t)count, fp) != count) {
            fclose(fp);
            return 0;
        }
    }

    fclose(fp);
    return 1;
}

int storage_load(Component list[], int *count, int *next_id) {
    storage_ensure_dir();
    FILE *fp = fopen(DB_FILE_PATH, "rb");
    if (!fp) {
        storage_seed_defaults(list, count, next_id);
        storage_save(list, *count, *next_id);
        return 1;
    }

    LegacyFileHeader legacy;
    if (fread(&legacy, sizeof(LegacyFileHeader), 1, fp) != 1) {
        fclose(fp);
        storage_seed_defaults(list, count, next_id);
        storage_save(list, *count, *next_id);
        return 1;
    }

    int stored_count = 0;
    int stored_next_id = 0;
    int seed_version = 1;
    if (strcmp(legacy.magic, "ELDBv3") == 0) {
        stored_count = legacy.count;
        stored_next_id = legacy.next_id;
    } else if (strcmp(legacy.magic, "ELDBv4") == 0) {
        FileHeader header;
        rewind(fp);
        if (fread(&header, sizeof(FileHeader), 1, fp) != 1) {
            fclose(fp);
            storage_seed_defaults(list, count, next_id);
            storage_save(list, *count, *next_id);
            return 1;
        }
        stored_count = header.count;
        stored_next_id = header.next_id;
        seed_version = header.seed_version;
    } else {
        fclose(fp);
        storage_seed_defaults(list, count, next_id);
        storage_save(list, *count, *next_id);
        return 1;
    }

    if (stored_count < 0 || stored_count > MAX_COMPONENTS) {
        fclose(fp);
        storage_seed_defaults(list, count, next_id);
        storage_save(list, *count, *next_id);
        return 1;
    }

    if (stored_count > 0) {
        int read_items = (int)fread(list, sizeof(Component), (size_t)stored_count, fp);
        if (read_items != stored_count) {
            fclose(fp);
            return 0;
        }
    }

    *count = stored_count;
    *next_id = stored_next_id > 0 ? stored_next_id : (stored_count + 1);
    fclose(fp);

    if (seed_version < CATALOG_SEED_VERSION) {
        append_seed_expansion(list, count, next_id);
        return storage_save(list, *count, *next_id);
    }
    return 1;
}

int storage_reset_default(Component list[], int *count, int *next_id) {
    remove(DB_FILE_PATH);
    storage_seed_defaults(list, count, next_id);
    return storage_save(list, *count, *next_id);
}
